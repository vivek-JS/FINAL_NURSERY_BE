// Helper function to create inventory transaction
const createInventoryTransaction = async (item, grn, user, balanceBefore, balanceAfter) => {
  const transactionNumber = await InventoryTransaction.generateTransactionNumber();

  const transaction = new InventoryTransaction({
    transactionNumber,
    transactionType: 'inward',
    product: item.product,
    batch: item.batch,
    quantity: item.acceptedQuantity,
    unit: item.unit,
    balanceBeforeTransaction: balanceBefore,
    balanceAfterTransaction: balanceAfter,
    rate: item.rate,
    value: item.amount,
    referenceType: 'GRN',
    referenceId: grn._id,
    referenceNumber: grn.grnNumber,
    toLocation: 'Main Warehouse',
    reason: 'GRN Entry',
    performedBy: user._id,
  });

  await transaction.save();
  return transaction;
};

// Helper function to generate batch number
const generateBatchNumber = async (productNameOrId, productId = null) => {
  let productName = 'PROD';
  let prodId = productId;
  
  // If first param is ObjectId, fetch product
  if (typeof productNameOrId === 'string' && productNameOrId.length === 24 && !productNameOrId.includes(' ')) {
    // Looks like ObjectId
    const Product = (await import('../models/product.model.js')).default;
    const product = await Product.findById(productNameOrId);
    if (product) {
      productName = product.name;
      prodId = productNameOrId;
    }
  } else {
    // First param is product name
    productName = productNameOrId || 'PROD';
    prodId = productId || productNameOrId;
  }
  
  const date = new Date();
  const year = date.getFullYear().toString().slice(-2);
  const month = (date.getMonth() + 1).toString().padStart(2, '0');
  const day = date.getDate().toString().padStart(2, '0');
  const productCode = productName.substring(0, 3).toUpperCase().replace(/\s/g, '');
  const random = Math.floor(Math.random() * 1000).toString().padStart(3, '0');
  const productIdShort = prodId ? prodId.toString().slice(-3) : '000';
  return `BATCH${productCode}${year}${month}${day}${random}`;
};

// Create GRN
export const createGRN = async (req, res) => {
  try {
    // Handle FormData - parse JSON fields
    let items = [];
    let additionalItems = [];
    let purchaseOrder = null;
    
    if (req.body.items) {
      items = typeof req.body.items === 'string' ? JSON.parse(req.body.items) : req.body.items;
    }
    if (req.body.additionalItems) {
      additionalItems = typeof req.body.additionalItems === 'string' ? JSON.parse(req.body.additionalItems) : req.body.additionalItems;
    }
    if (req.body.purchaseOrder) {
      purchaseOrder = typeof req.body.purchaseOrder === 'string' ? req.body.purchaseOrder : req.body.purchaseOrder;
    }

    let {
      supplier,
      invoiceNumber,
      invoiceDate,
      challanNumber,
      challanDate,
      vehicleNumber,
      driverName,
      freightCharges,
      otherCharges,
      notes,
    } = req.body;

    // Combine items and additionalItems
    const allItems = [...items, ...additionalItems];

    // If supplier is null but purchaseOrder is provided, get supplier from PO
    if (!supplier && purchaseOrder) {
      const PurchaseOrder = (await import('../models/purchaseOrder.model.js')).default;
      const po = await PurchaseOrder.findById(purchaseOrder);
      if (po && po.supplier) {
        supplier = po.supplier._id || po.supplier;
      }
    }

    // Process uploaded images - save to attachments (optional for auto-generated GRN)
    const attachments = [];
    if (req.files && req.files.length > 0) {
      // For now, store file info - in production, upload to cloud storage (Cloudinary/S3)
      for (const file of req.files) {
        attachments.push({
          name: file.originalname,
          url: `/uploads/grn/${Date.now()}-${file.originalname}`, // Will be uploaded to storage
          type: file.mimetype,
          // In production, upload to Cloudinary/S3 and store the URL
        });
      }
    }

    // Validate images are uploaded (mandatory only for manual GRN creation, not auto-generated)
    // Check if this is an auto-generated GRN (has purchaseOrder and no files)
    const isAutoGenerated = purchaseOrder && (!req.files || req.files.length === 0);
    if (!isAutoGenerated && (!req.files || req.files.length === 0)) {
      return res.status(400).json({
        success: false,
        message: 'At least one image is required for GRN',
      });
    }

    // Auto-generate batch numbers for items that don't have one or are blank
    // batchNumber and lotNumber are treated as the same field
    if (allItems && Array.isArray(allItems)) {
      for (const item of allItems) {
        // Use lotNumber if batchNumber is empty, or vice versa (they're the same)
        if (!item.batchNumber || !item.batchNumber.trim()) {
          if (item.lotNumber && item.lotNumber.trim()) {
            item.batchNumber = item.lotNumber.trim();
          } else {
            item.batchNumber = await generateBatchNumber(item.product);
          }
        } else {
          // If batchNumber exists, also set lotNumber to the same value
          item.lotNumber = item.batchNumber.trim();
        }
        
        // Ensure expiryDate is provided (mandatory)
        if (!item.expiryDate) {
          return res.status(400).json({
            success: false,
            message: `Expiry date is required for all items. Missing for product: ${item.product}`,
          });
        }
      }
    }

    // Generate GRN number
    const grnNumber = await GRN.generateGRNNumber();

    // Calculate totals
    let subtotal = 0;
    let gstAmount = 0;

    allItems.forEach((item) => {
      subtotal += item.amount || 0;
      // GST calculation if needed
    });

    const totalAmount = subtotal + gstAmount + (freightCharges || 0) + (otherCharges || 0);

    const grn = new GRN({
      grnNumber,
      supplier,
      purchaseOrder,
      invoiceNumber,
      invoiceDate,
      challanNumber,
      challanDate,
      vehicleNumber,
      driverName,
      items: allItems, // Combined items and additionalItems
      subtotal,
      gstAmount,
      freightCharges: freightCharges || 0,
      otherCharges: otherCharges || 0,
      totalAmount,
      attachments, // Add uploaded images
      notes,
      createdBy: req.user._id,
    });

    await grn.save();
    
    // Populate without supplier first, then handle supplier/merchant separately
    await grn.populate(['purchaseOrder', 'items.product', 'items.unit', 'createdBy']);
    
    // Handle supplier/merchant population using Merchant model
    if (grn.supplier) {
      const { default: Merchant } = await import('../models/merchant.model.js');
      const { default: Supplier } = await import('../models/supplier.model.js');
      
      const supplierId = grn.supplier._id || grn.supplier;
      const supplierDoc = await Supplier.findById(supplierId);
      if (supplierDoc) {
        grn.supplier = supplierDoc;
      } else {
        const merchant = await Merchant.findById(supplierId);
        if (merchant) {
          grn.supplier = {
            _id: merchant._id,
            name: merchant.name,
            phone: merchant.phone,
            email: merchant.email,
            address: merchant.address,
            gstin: merchant.gstin,
            contactPerson: merchant.contactPerson,
            type: 'merchant',
            category: merchant.category,
          };
        }
      }
    }

    res.status(201).json({
      success: true,
      message: 'GRN created successfully',
      data: grn,
    });
  } catch (error) {
    console.error('Error creating GRN:', error);
    res.status(500).json({
      success: false,
      message: 'Error creating GRN',
      error: error.message,
    });
  }
};

// Approve GRN and update inventory
export const approveGRN = async (req, res) => {
  try {
    const { id } = req.params;
    const { qualityCheckRemarks } = req.body;

    const grn = await GRN.findById(id);

    if (!grn) {
      return res.status(404).json({
        success: false,
        message: 'GRN not found',
      });
    }

    if (grn.status === 'approved') {
      return res.status(400).json({
        success: false,
        message: 'GRN already approved',
      });
    }

    // Create batches and update inventory
    for (const item of grn.items) {
      if (item.acceptedQuantity > 0) {
        // Ensure batch number exists - auto-generate if blank
        // batchNumber and lotNumber are treated as the same field
        let batchNumber = item.batchNumber || item.lotNumber;
        if (!batchNumber || !batchNumber.trim()) {
          batchNumber = await generateBatchNumber(item.product);
        }
        // Ensure both fields have the same value
        item.batchNumber = batchNumber.trim();
        item.lotNumber = batchNumber.trim();

        // Check if batch number already exists
        const existingBatch = await Batch.findOne({ batchNumber: batchNumber.trim() });
        if (existingBatch) {
          // If batch exists, append timestamp to make it unique
          const timestamp = Date.now().toString().slice(-6);
          batchNumber = `${batchNumber.trim()}_${timestamp}`;
        }

        // Convert expiryDate from string to Date if needed
        let expiryDate = item.expiryDate;
        if (expiryDate && typeof expiryDate === 'string') {
          expiryDate = new Date(expiryDate);
          // Check if date is valid
          if (isNaN(expiryDate.getTime())) {
            expiryDate = undefined;
          }
        }
        
        let manufactureDate = item.manufactureDate;
        if (manufactureDate && typeof manufactureDate === 'string') {
          manufactureDate = new Date(manufactureDate);
          // Check if date is valid
          if (isNaN(manufactureDate.getTime())) {
            manufactureDate = undefined;
          }
        }

        // Create batch
        const batch = new Batch({
          batchNumber: batchNumber.trim(),
          product: item.product,
          manufactureDate: manufactureDate || undefined,
          expiryDate: expiryDate || undefined,
          receivedDate: grn.grnDate,
          supplier: grn.supplier,
          purchasePrice: item.rate,
          quantity: item.acceptedQuantity,
          remainingQuantity: item.acceptedQuantity,
          unit: item.unit,
          grn: grn._id,
          createdBy: req.user._id,
        });

        await batch.save();
        
        // Update item with batch reference and batch number (in case it was auto-generated)
        item.batch = batch._id;
        item.batchNumber = batchNumber.trim();

        // Update product stock
        const product = await Product.findById(item.product);
        if (!product) {
          throw new Error(`Product not found for item: ${item.product}`);
        }

        // Store old values for transaction
        const oldStock = product.currentStock || 0;
        const oldValue = product.stockValue || 0;

        // Update stock values
        product.currentStock = (product.currentStock || 0) + item.acceptedQuantity;
        product.stockValue = (product.stockValue || 0) + item.amount;
        
        // Calculate average price safely (handles division by zero)
        if (product.currentStock > 0) {
          product.averagePrice = product.stockValue / product.currentStock;
        } else {
          product.averagePrice = 0;
        }
        
        product.updatedBy = req.user._id;

        // Save product and verify it was saved
        try {
          await product.save();
          console.log(`Stock updated for product ${item.product}: ${oldStock} -> ${product.currentStock}`);
        } catch (saveError) {
          console.error(`Error saving product ${item.product}:`, saveError);
          throw new Error(`Failed to update stock for product: ${saveError.message}`);
        }
        
        // Verify stock was updated by re-fetching
        const updatedProduct = await Product.findById(item.product);
        if (updatedProduct.currentStock !== product.currentStock) {
          console.error(`Stock update mismatch for product ${item.product}. Expected: ${product.currentStock}, Got: ${updatedProduct.currentStock}`);
          // Force update using findByIdAndUpdate
          await Product.findByIdAndUpdate(item.product, {
            currentStock: product.currentStock,
            stockValue: product.stockValue,
            averagePrice: product.averagePrice,
            updatedBy: req.user._id,
          });
        }

        // Create inventory transaction with correct balance values
        await createInventoryTransaction(item, grn, req.user, oldStock, product.currentStock);

        // Update slot availablePlants if slotId is provided
        if (item.slotId) {
          try {
            console.log(`🔄 Attempting to update slot ${item.slotId} with quantity ${item.acceptedQuantity}`);
            const { default: PlantSlot } = await import('../models/slots.model.js');
            const mongoose = await import('mongoose');
            
            // Convert slotId to ObjectId if it's a string
            let slotObjectId;
            try {
              slotObjectId = typeof item.slotId === 'string' 
                ? new mongoose.default.Types.ObjectId(item.slotId)
                : item.slotId;
            } catch (e) {
              console.error(`❌ Invalid slotId format: ${item.slotId}`, e);
              throw new Error(`Invalid slotId format: ${item.slotId}`);
            }
            
            // Find the slot document - try both ObjectId and string formats
            let plantSlotDoc = await PlantSlot.findOne({
              "subtypeSlots.slots._id": slotObjectId
            });
            
            // If not found with ObjectId, try with string
            if (!plantSlotDoc) {
              plantSlotDoc = await PlantSlot.findOne({
                "subtypeSlots.slots._id": item.slotId
              });
            }
            
            if (!plantSlotDoc) {
              console.warn(`⚠️ Slot ${item.slotId} not found in database - searching all years...`);
              // Try searching without year filter (slot might be in different year)
              const allSlots = await PlantSlot.find({
                "subtypeSlots.slots._id": slotObjectId
              }).limit(5);
              
              if (allSlots.length > 0) {
                plantSlotDoc = allSlots[0];
                console.log(`✅ Found slot in year ${plantSlotDoc.year}`);
              } else {
                console.warn(`⚠️ Slot ${item.slotId} not found in any year`);
              }
            }
            
            if (plantSlotDoc) {
              // Find the slot in the document
              let slotFound = false;
              let currentAvailablePlants = 0;
              let targetSlot = null;
              let targetSubtypeIndex = -1;
              let targetSlotIndex = -1;
              
              for (let i = 0; i < (plantSlotDoc.subtypeSlots || []).length; i++) {
                const subtypeSlot = plantSlotDoc.subtypeSlots[i];
                for (let j = 0; j < (subtypeSlot.slots || []).length; j++) {
                  const slot = subtypeSlot.slots[j];
                  if (slot._id && slot._id.toString() === slotObjectId.toString()) {
                    slotFound = true;
                    targetSlot = slot;
                    targetSubtypeIndex = i;
                    targetSlotIndex = j;
                    currentAvailablePlants = slot.availablePlants || 0;
                    console.log(`✅ Found slot: availablePlants before = ${currentAvailablePlants}, year = ${plantSlotDoc.year}`);
                    break;
                  }
                }
                if (slotFound) break;
              }
              
              if (slotFound && targetSlot) {
                // Method 1: Try updateOne with arrayFilters
                const updateResult = await PlantSlot.updateOne(
                  { 
                    _id: plantSlotDoc._id,
                    "subtypeSlots.slots._id": slotObjectId 
                  },
                  {
                    $inc: {
                      "subtypeSlots.$[subtypeSlot].slots.$[slot].availablePlants": item.acceptedQuantity
                    }
                  },
                  {
                    arrayFilters: [
                      { "subtypeSlot.slots._id": slotObjectId },
                      { "slot._id": slotObjectId }
                    ]
                  }
                );

                console.log(`📊 Slot update result: matched=${updateResult.matchedCount}, modified=${updateResult.modifiedCount}`);
                
                if (updateResult.matchedCount > 0 && updateResult.modifiedCount > 0) {
                  console.log(`✅ Updated slot ${item.slotId} availablePlants by +${item.acceptedQuantity}`);
                  
                  // Verify the update
                  await plantSlotDoc.populate();
                  const updatedSlot = plantSlotDoc.subtypeSlots[targetSubtypeIndex]?.slots[targetSlotIndex];
                  if (updatedSlot) {
                    console.log(`✅ Verified: availablePlants after = ${updatedSlot.availablePlants || 0}`);
                  }
                } else {
                  // Method 2: Direct update using array indices
                  console.log(`⚠️ ArrayFilters method failed, trying direct update...`);
                  const newAvailablePlants = currentAvailablePlants + item.acceptedQuantity;
                  plantSlotDoc.subtypeSlots[targetSubtypeIndex].slots[targetSlotIndex].availablePlants = newAvailablePlants;
                  await plantSlotDoc.save();
                  console.log(`✅ Updated slot using direct method: availablePlants = ${newAvailablePlants}`);
                }
              } else {
                console.warn(`⚠️ Slot ${item.slotId} not found in document structure`);
              }
            } else {
              console.warn(`⚠️ Could not find slot document for slotId: ${item.slotId}`);
            }
          } catch (slotError) {
            console.error(`❌ Error updating slot ${item.slotId}:`, slotError);
            console.error(`   Error details:`, slotError.message);
            console.error(`   Stack:`, slotError.stack);
            // Don't fail the GRN approval if slot update fails, just log it
          }
        } else {
          console.log(`ℹ️ No slotId provided for item, skipping slot update`);
        }
      }
    }

    // Update GRN status
    grn.status = 'approved';
    grn.qualityCheckBy = req.user._id;
    grn.qualityCheckDate = new Date();
    grn.qualityCheckRemarks = qualityCheckRemarks;
    grn.updatedBy = req.user._id;

    await grn.save();

    // Update PO if linked
    if (grn.purchaseOrder) {
      const po = await PurchaseOrder.findById(grn.purchaseOrder);
      if (po) {
        // Update received quantities
        grn.items.forEach((grnItem) => {
          const poItem = po.items.find(
            (item) => item.product.toString() === grnItem.product.toString()
          );
          if (poItem) {
            poItem.receivedQuantity += grnItem.acceptedQuantity;
          }
        });

        // Check if PO is fully received
        const allReceived = po.items.every(
          (item) => item.receivedQuantity >= item.quantity
        );

        if (allReceived) {
          po.status = 'received';
        } else {
          po.status = 'partial_received';
        }

        await po.save();
      }
    }

    await grn.populate(['purchaseOrder', 'items.product', 'items.unit', 'items.batch']);
    
    // Handle supplier/merchant population
    if (grn.supplier) {
      const { default: Merchant } = await import('../models/merchant.model.js');
      const { default: Supplier } = await import('../models/supplier.model.js');
      
      const supplierId = grn.supplier._id || grn.supplier;
      const supplierDoc = await Supplier.findById(supplierId);
      if (supplierDoc) {
        grn.supplier = supplierDoc;
      } else {
        const merchant = await Merchant.findById(supplierId);
        if (merchant) {
          grn.supplier = {
            _id: merchant._id,
            name: merchant.name,
            phone: merchant.phone,
            email: merchant.email,
            address: merchant.address,
            gstin: merchant.gstin,
            contactPerson: merchant.contactPerson,
            type: 'merchant',
            category: merchant.category,
          };
        }
      }
    }

    res.json({
      success: true,
      message: 'GRN approved and inventory updated successfully',
      data: grn,
    });
  } catch (error) {
    console.error('Error approving GRN:', error);
    res.status(500).json({
      success: false,
      message: 'Error approving GRN',
      error: error.message,
    });
  }
};

// Get all GRNs
export const getAllGRNs = async (req, res) => {
  try {
    const {
      supplier,
      status,
      search,
      startDate,
      endDate,
      page = 1,
      limit = 20,
    } = req.query;

    const query = {};

    if (supplier) {
      query.supplier = supplier;
    }

    if (status) {
      query.status = status;
    }

    if (search) {
      query.$or = [
        { grnNumber: { $regex: search, $options: 'i' } },
        { invoiceNumber: { $regex: search, $options: 'i' } },
        { challanNumber: { $regex: search, $options: 'i' } },
      ];
    }

    if (startDate || endDate) {
      query.grnDate = {};
      if (startDate) query.grnDate.$gte = new Date(startDate);
      if (endDate) query.grnDate.$lte = new Date(endDate);
    }

    const skip = (parseInt(page) - 1) * parseInt(limit);

    // Use lean() to get plain objects that we can modify
    // Don't populate supplier here since it might be Merchant or Supplier
    const grns = await GRN.find(query)
      .populate([
        'purchaseOrder', 
        'items.product', 
        'items.unit', 
        'items.batch', 
        'createdBy',
        'qualityCheckBy',
        'updatedBy',
      ])
      .sort({ grnDate: -1 })
      .skip(skip)
      .limit(parseInt(limit))
      .lean(); // Convert to plain objects so we can modify them

    // Handle supplier/merchant population for each GRN
    const { default: Merchant } = await import('../models/merchant.model.js');
    const { default: Supplier } = await import('../models/supplier.model.js');
    
    for (const grn of grns) {
      if (grn.supplier) {
        // Handle both ObjectId and string ID
        let supplierId = grn.supplier;
        
        // If it's already populated (object with _id), extract the ID
        if (typeof supplierId === 'object' && supplierId !== null) {
          if (supplierId._id) {
            supplierId = supplierId._id;
          } else if (supplierId.toString) {
            supplierId = supplierId.toString();
          }
        }
        
        // Convert to string if it's an ObjectId
        if (typeof supplierId !== 'string') {
          supplierId = supplierId.toString();
        }
        
        // Try Supplier first
        const supplierDoc = await Supplier.findById(supplierId).lean();
        if (supplierDoc) {
          grn.supplier = {
            _id: supplierDoc._id,
            name: supplierDoc.name,
            displayName: supplierDoc.name,
            phone: supplierDoc.phone,
            email: supplierDoc.email,
            address: supplierDoc.address,
            gstin: supplierDoc.gstin,
            contactPerson: supplierDoc.contactPerson,
            type: 'supplier',
          };
        } else {
          // Try Merchant (since supplier field can contain merchant ID)
          const merchant = await Merchant.findById(supplierId).lean();
          if (merchant) {
            grn.supplier = {
              _id: merchant._id,
              name: merchant.name,
              displayName: merchant.name,
              phone: merchant.phone,
              email: merchant.email,
              address: merchant.address,
              gstin: merchant.gstin,
              contactPerson: merchant.contactPerson,
              type: 'merchant',
              category: merchant.category,
            };
          } else {
            // If neither found, keep as ID but add a placeholder
            console.log(`⚠️ Supplier/Merchant not found for ID: ${supplierId} in GRN ${grn.grnNumber}`);
            grn.supplier = {
              _id: supplierId,
              name: 'Unknown Supplier',
              displayName: 'Unknown Supplier',
            };
          }
        }
      } else {
        // If supplier is null or undefined, set a placeholder
        grn.supplier = {
          _id: null,
          name: 'No Supplier',
          displayName: 'No Supplier',
        };
      }
    }

    const total = await GRN.countDocuments(query);

    // Debug: Log first GRN supplier to verify it's populated
    if (grns.length > 0) {
      console.log('📦 Sample GRN supplier:', JSON.stringify(grns[0].supplier, null, 2));
      console.log('📦 Sample GRN supplier ID (raw):', grns[0].supplier?._id || grns[0].supplier);
    }

    res.json({
      success: true,
      data: grns,
      pagination: {
        total,
        page: parseInt(page),
        limit: parseInt(limit),
        pages: Math.ceil(total / parseInt(limit)),
      },
    });
  } catch (error) {
    console.error('Error fetching GRNs:', error);
    res.status(500).json({
      success: false,
      message: 'Error fetching GRNs',
      error: error.message,
    });
  }
};

// Get GRN by ID
export const getGRNById = async (req, res) => {
  try {
    const grn = await GRN.findById(req.params.id)
      .populate([
        'purchaseOrder',
        'items.product',
        'items.unit',
        'items.batch',
        'createdBy',
        'updatedBy',
        'qualityCheckBy',
        {
          path: 'supplier',
          model: 'Supplier',
          select: 'name phone email address gstin contactPerson',
        }
      ])
      .lean(); // Use lean() for better performance and to ensure all fields are returned

    if (!grn) {
      return res.status(404).json({
        success: false,
        message: 'GRN not found',
      });
    }

    // Handle supplier/merchant population using Merchant model
    if (grn.supplier) {
      const { default: Merchant } = await import('../models/merchant.model.js');
      const { default: Supplier } = await import('../models/supplier.model.js');
      
      // Handle both ObjectId and string ID
      let supplierId = grn.supplier;
      if (typeof supplierId === 'object' && supplierId._id) {
        supplierId = supplierId._id;
      } else if (typeof supplierId === 'object' && supplierId.toString) {
        supplierId = supplierId.toString();
      } else if (typeof supplierId !== 'string') {
        supplierId = supplierId.toString();
      }
      
      // Try Supplier first
      const supplierDoc = await Supplier.findById(supplierId);
      if (supplierDoc) {
        grn.supplier = {
          _id: supplierDoc._id,
          name: supplierDoc.name,
          displayName: supplierDoc.name,
          phone: supplierDoc.phone,
          email: supplierDoc.email,
          address: supplierDoc.address,
          gstin: supplierDoc.gstin,
          contactPerson: supplierDoc.contactPerson,
          type: 'supplier',
        };
      } else {
        // Try Merchant
        const merchant = await Merchant.findById(supplierId);
        if (merchant) {
          grn.supplier = {
            _id: merchant._id,
            name: merchant.name,
            displayName: merchant.name,
            phone: merchant.phone,
            email: merchant.email,
            address: merchant.address,
            gstin: merchant.gstin,
            contactPerson: merchant.contactPerson,
            type: 'merchant',
            category: merchant.category,
          };
        } else {
          // If neither found, keep as ID but add a placeholder
          grn.supplier = {
            _id: supplierId,
            name: 'Unknown Supplier',
            displayName: 'Unknown Supplier',
          };
        }
      }
    }

    res.json({
      success: true,
      data: grn,
    });
  } catch (error) {
    console.error('Error fetching GRN:', error);
    res.status(500).json({
      success: false,
      message: 'Error fetching GRN',
      error: error.message,
    });
  }
};

// Update GRN
export const updateGRN = async (req, res) => {
  try {
    const grn = await GRN.findById(req.params.id);

    if (!grn) {
      return res.status(404).json({
        success: false,
        message: 'GRN not found',
      });
    }

    if (grn.status === 'approved') {
      return res.status(400).json({
        success: false,
        message: 'Cannot update approved GRN',
      });
    }

    const updateFields = [
      'invoiceNumber',
      'invoiceDate',
      'challanNumber',
      'challanDate',
      'vehicleNumber',
      'driverName',
      'items',
      'freightCharges',
      'otherCharges',
      'notes',
    ];

    updateFields.forEach((field) => {
      if (req.body[field] !== undefined) {
        grn[field] = req.body[field];
      }
    });

    // Recalculate totals if items changed
    if (req.body.items) {
      let subtotal = 0;
      let gstAmount = 0;

      grn.items.forEach((item) => {
        subtotal += item.amount;
      });

      grn.subtotal = subtotal;
      grn.gstAmount = gstAmount;
      grn.totalAmount = subtotal + gstAmount + grn.freightCharges + grn.otherCharges;
    }

    grn.updatedBy = req.user._id;
    await grn.save();

    await grn.populate(['purchaseOrder', 'items.product', 'items.unit']);
    
    // Handle supplier/merchant population using Merchant model
    if (grn.supplier) {
      const { default: Merchant } = await import('../models/merchant.model.js');
      const { default: Supplier } = await import('../models/supplier.model.js');
      
      const supplierId = grn.supplier._id || grn.supplier;
      const supplierDoc = await Supplier.findById(supplierId);
      if (supplierDoc) {
        grn.supplier = supplierDoc;
      } else {
        const merchant = await Merchant.findById(supplierId);
        if (merchant) {
          grn.supplier = {
            _id: merchant._id,
            name: merchant.name,
            phone: merchant.phone,
            email: merchant.email,
            address: merchant.address,
            gstin: merchant.gstin,
            contactPerson: merchant.contactPerson,
            type: 'merchant',
            category: merchant.category,
          };
        }
      }
    }

    res.json({
      success: true,
      message: 'GRN updated successfully',
      data: grn,
    });
  } catch (error) {
    console.error('Error updating GRN:', error);
    res.status(500).json({
      success: false,
      message: 'Error updating GRN',
      error: error.message,
    });
  }
};

